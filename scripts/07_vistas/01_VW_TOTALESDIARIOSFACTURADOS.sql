CREATE OR ALTER VIEW DBO.VW_TOTALESDIARIOSFACTURADOS
AS
SELECT
    CAST(F.FECHA_EMISION AS DATE) AS FECHA_EMISION,
    E.RAZON_SOCIAL AS NOMBRE_EMPRESA,
    TD.DESCRIPCION AS TIPO_DOCUMENTO,
    COUNT(F.IDENTIFICADOR) AS CANTIDAD_FACTURAS,
    SUM(F.SUBTOTAL) AS SUBTOTAL_ACUMULADO,
    SUM(F.TOTAL_DESCUENTOS) AS TOTAL_DESCUENTOS,
    SUM(F.IMPUESTOS_APLICADOS) AS TOTAL_IMPUESTOS,
    SUM(F.MONTO_TOTAL) AS MONTO_TOTAL_FACTURADO
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA_EMISORA AS E
    ON F.ID_EMPRESA = E.ID_EMPRESA
INNER JOIN DBO.TIPO_DOCUMENTO AS TD
    ON F.COD_IDENTIFICADOR_TIPO = TD.COD_IDENTIFICADOR
GROUP BY
    CAST(F.FECHA_EMISION AS DATE),
    E.ID_EMPRESA,
    E.RAZON_SOCIAL,
    TD.COD_IDENTIFICADOR,
    TD.DESCRIPCION;
GO
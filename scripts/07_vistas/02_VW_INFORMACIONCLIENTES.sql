CREATE OR ALTER VIEW DBO.VW_INFORMACIONCLIENTES
AS
SELECT
    C.CEDULA,
    C.NOMBRE_RAZON_SOCIAL AS NOMBRE_O_RAZON_SOCIAL,
    COUNT(F.IDENTIFICADOR) AS CANTIDAD_FACTURAS,
    CASE
        WHEN
            SUM(
                CASE
                    WHEN F.FECHA_EMISION >= DATEADD(MONTH, -6, GETDATE())
                        THEN 1
                    ELSE 0
                END
            ) > 5
            THEN 'Sí'
        ELSE 'No'
    END AS CLIENTE_FRECUENTE
FROM DBO.CLIENTE AS C
LEFT JOIN DBO.FACTURA AS F
    ON C.ID_CLIENTE = F.ID_CLIENTE
GROUP BY
    C.ID_CLIENTE,
    C.CEDULA,
    C.NOMBRE_RAZON_SOCIAL;
GO

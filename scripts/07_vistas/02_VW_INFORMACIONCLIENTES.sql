USE SISTEMADEFACTURACION;
GO

CREATE OR ALTER VIEW DBO.VW_INFORMACIONCLIENTES
AS
-- PARTE 1: CLIENTES FÍSICOS
SELECT
    CF.CEDULA,
    CAST(CF.NOMBRE + ' ' + CF.APELLIDO1 + ' ' + ISNULL(CF.APELLIDO2, '') AS VARCHAR(100)) AS NOMBRE_O_RAZON_SOCIAL,
    COUNT(F.IDENTIFICADOR) AS CANTIDAD_FACTURAS,
    CASE
        WHEN
            SUM(
                CASE
                    WHEN F.FECHA_EMISION >= DATEADD(MONTH, -6, GETDATE())
                        THEN 1
                    ELSE 0
                END
            ) > 5
            THEN 'Sí'
        ELSE 'No'
    END AS CLIENTE_FRECUENTE
FROM DBO.CLIENTE_FISICO AS CF
LEFT JOIN DBO.FACTURA AS F
    ON CF.ID_CLIENTE = F.ID_CLIENTE_FISICO
GROUP BY
    CF.ID_CLIENTE,
    CF.CEDULA,
    CF.NOMBRE,
    CF.APELLIDO1,
    CF.APELLIDO2

UNION ALL
-- PARTE 2: CLIENTES JURÍDICOS
SELECT
    CJ.CEDULA,
    CJ.RAZON_SOCIAL AS NOMBRE_O_RAZON_SOCIAL,
    COUNT(F.IDENTIFICADOR) AS CANTIDAD_FACTURAS,
    CASE
        WHEN
            SUM(
                CASE
                    WHEN F.FECHA_EMISION >= DATEADD(MONTH, -6, GETDATE())
                        THEN 1
                    ELSE 0
                END
            ) > 5
            THEN 'Sí'
        ELSE 'No'
    END AS CLIENTE_FRECUENTE
FROM DBO.CLIENTE_JURIDICO AS CJ
LEFT JOIN DBO.FACTURA AS F
    ON CJ.ID_CLIENTE = F.ID_CLIENTE_JURIDICO
GROUP BY
    CJ.ID_CLIENTE,
    CJ.CEDULA,
    CJ.RAZON_SOCIAL;
GO

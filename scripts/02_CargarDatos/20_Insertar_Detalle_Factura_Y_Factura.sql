USE SISTEMADEFACTURACION;
GO

SET NOCOUNT ON;

DECLARE @T_TOTAL DATETIME2 = SYSDATETIME();
DECLARE @T DATETIME2 = SYSDATETIME();
DECLARE @CANT_FACTURAS INT = 500000;
DECLARE @LOTE INT = 50000;
DECLARE @COD INT = 0;
DECLARE @MSG VARCHAR(500) = '';
DECLARE @CONTADOR INT;
DECLARE @SQL NVARCHAR(MAX);

DROP TABLE IF EXISTS #EMPRESAS;
DROP TABLE IF EXISTS #CLIENTES;
DROP TABLE IF EXISTS #MONEDAS;
DROP TABLE IF EXISTS #TIPOS;
DROP TABLE IF EXISTS #ITEMS;
DROP TABLE IF EXISTS #BASE;
DROP TABLE IF EXISTS #FACT;
DROP TABLE IF EXISTS #DET;
DROP TABLE IF EXISTS #INDICES;

SELECT
    CAST(ROW_NUMBER() OVER (ORDER BY ID_EMPRESA) AS INT) AS N,
    ID_EMPRESA
INTO #EMPRESAS
FROM EMPRESA_EMISORA
WHERE INDICADOR = 1;

SELECT
    CAST(ROW_NUMBER() OVER (ORDER BY ID_CLIENTE) AS INT) AS N,
    ID_CLIENTE
INTO #CLIENTES
FROM CLIENTE;

SELECT
    CAST(
        ROW_NUMBER() OVER (ORDER BY COD_IDENTIFICADOR) AS INT
    ) AS N,
    COD_IDENTIFICADOR AS COD_MONEDA
INTO #MONEDAS
FROM MONEDAS;

SELECT
    CAST(
        ROW_NUMBER() OVER (ORDER BY COD_IDENTIFICADOR) AS INT
    ) AS N,
    COD_IDENTIFICADOR AS COD_TIPO
INTO #TIPOS
FROM TIPO_DOCUMENTO;

SELECT TOP (3)
    CAST(
        ROW_NUMBER() OVER (ORDER BY ID_PRODUCTO) AS INT
    ) AS NUMERO_CORRELATIVO,
    ID_PRODUCTO,
    DESCRIPCION,
    PRECIO_UNITARIO,
    PORCENTAJE_IMPUESTO,
    CAST(
        ROW_NUMBER() OVER (ORDER BY ID_PRODUCTO) AS DECIMAL(18, 2)
    ) AS CANTIDAD
INTO #ITEMS
FROM PRODUCTOS
WHERE ESTADO = 1
ORDER BY ID_PRODUCTO;

DECLARE @N_EMPRESAS INT = (SELECT COUNT(*) FROM #EMPRESAS);
DECLARE @N_CLIENTES INT = (SELECT COUNT(*) FROM #CLIENTES);
DECLARE @N_MONEDAS INT = (SELECT COUNT(*) FROM #MONEDAS);
DECLARE @N_TIPOS INT = (SELECT COUNT(*) FROM #TIPOS);
DECLARE @N_ITEMS INT = (SELECT COUNT(*) FROM #ITEMS);

IF EXISTS (SELECT 1 FROM FACTURA)
    BEGIN
        RAISERROR (
            'Ya existen facturas. Ejecute limpiar_facturas.sql antes de cargar.',  -- noqa: LT05
            16, 1
        );
        RETURN;
    END;

IF @N_EMPRESAS = 0 OR @N_CLIENTES = 0 OR @N_MONEDAS = 0 OR @N_TIPOS = 0
    BEGIN
        RAISERROR (
            'Faltan datos maestros (empresas, clientes, monedas o tipos de documento).',  -- noqa: LT05
            16, 1
        );
        RETURN;
    END;

IF @N_ITEMS < 3
    BEGIN
        RAISERROR (
            'Se necesitan al menos 3 productos activos para los detalles.',
            16, 1
        );
        RETURN;
    END;

IF (
    SELECT COUNT(*)
    FROM ESTADO_FACTURA
    WHERE ESTADO IN ('BORRADOR', 'EMITIDA', 'PAGADA', 'CANCELADA')
) < 4
    BEGIN
        RAISERROR (
            'Faltan estados en ESTADO_FACTURA (BORRADOR, EMITIDA, PAGADA, CANCELADA).',  -- noqa: LT05
            16, 1
        );
        RETURN;
    END;

DECLARE @AHORA DATETIME = GETDATE();
DECLARE @INICIO DATETIME = DATEADD(YEAR, -1, @AHORA);
DECLARE @PASO INT = DATEDIFF(SECOND, @INICIO, @AHORA) / @CANT_FACTURAS;

IF @PASO < 1
    BEGIN
        RAISERROR (
            'Demasiadas facturas para repartirlas en un anio sin repetir identificadores.',  -- noqa: LT05
            16, 1
        );
        RETURN;
    END;

SELECT TOP (@CANT_FACTURAS)
    CAST(ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS INT) AS N,
    (CHECKSUM(NEWID()) & 2147483647) AS R_EMPRESA,
    (CHECKSUM(NEWID()) & 2147483647) AS R_CLIENTE,
    (CHECKSUM(NEWID()) & 2147483647) AS R_MONEDA,
    (CHECKSUM(NEWID()) & 2147483647) AS R_TIPO,
    (CHECKSUM(NEWID()) & 2147483647) % 100 AS R_ESTADO,
    (CHECKSUM(NEWID()) & 2147483647) % @PASO AS SEGUNDOS_EXTRA,
    (CHECKSUM(NEWID()) & 2147483647) % 99001 AS R_SUBTOTAL,
    (CHECKSUM(NEWID()) & 2147483647) % 21 AS R_DESCUENTO
INTO #BASE
FROM SYS.ALL_OBJECTS AS A
CROSS JOIN SYS.ALL_OBJECTS AS B;

-- noqa: disable=ST05
SELECT
    B.N,
    X.TS AS FECHA_HORA,
    EM.ID_EMPRESA,
    CL.ID_CLIENTE,
    MO.COD_MONEDA,
    TI.COD_TIPO,
    E.COD_IDENTIFICADOR AS COD_ESTADO,
    M1.SUBTOTAL,
    M2.DESCUENTO AS TOTAL_DESCUENTOS,
    M3.IMPUESTO AS IMPUESTOS_APLICADOS,
    CAST(
        M1.SUBTOTAL - M2.DESCUENTO + M3.IMPUESTO AS DECIMAL(18, 2)
    ) AS MONTO_TOTAL,
    CONVERT(CHAR(8), X.TS, 112)
    + REPLACE(CONVERT(CHAR(8), X.TS, 108), ':', '')
    + '-' + TI.COD_TIPO AS IDENTIFICADOR
INTO #FACT
FROM #BASE AS B
CROSS APPLY (
    SELECT DATEADD(SECOND, (B.N - 1) * @PASO + B.SEGUNDOS_EXTRA, @INICIO) AS TS
) AS X
CROSS APPLY (
    SELECT CAST(10 + B.R_SUBTOTAL / 100.0 AS DECIMAL(18, 2)) AS SUBTOTAL
) AS M1
CROSS APPLY (
    SELECT CAST(
        M1.SUBTOTAL * B.R_DESCUENTO / 100 AS DECIMAL(18, 2)
    ) AS DESCUENTO
) AS M2
CROSS APPLY (
    SELECT CAST(
        (M1.SUBTOTAL - M2.DESCUENTO) * 13 / 100 AS DECIMAL(18, 2)
    ) AS IMPUESTO
) AS M3
INNER JOIN #EMPRESAS AS EM
    ON EM.N = (B.R_EMPRESA % @N_EMPRESAS) + 1
INNER JOIN #CLIENTES AS CL
    ON CL.N = (B.R_CLIENTE % @N_CLIENTES) + 1
INNER JOIN #MONEDAS AS MO
    ON MO.N = (B.R_MONEDA % @N_MONEDAS) + 1
INNER JOIN #TIPOS AS TI
    ON TI.N = (B.R_TIPO % @N_TIPOS) + 1
INNER JOIN ESTADO_FACTURA AS E
    ON E.ESTADO = CASE
        WHEN B.R_ESTADO < 5 THEN 'BORRADOR'
        WHEN B.R_ESTADO < 35 THEN 'EMITIDA'
        WHEN B.R_ESTADO < 90 THEN 'PAGADA'
        ELSE 'CANCELADA'
    END;
-- noqa: enable=ST05

-- 3. Detalles: cada factura lleva los mismos 3 items (3 lineas por factura)
SELECT
    F.N,
    F.IDENTIFICADOR,
    I.NUMERO_CORRELATIVO,
    I.DESCRIPCION,
    I.CANTIDAD,
    I.PRECIO_UNITARIO,
    I.PORCENTAJE_IMPUESTO,
    I.ID_PRODUCTO
INTO #DET
FROM #FACT AS F
CROSS JOIN #ITEMS AS I;

PRINT 'Datos generados en temporales: '
+ CAST(
    CAST(
        DATEDIFF(MILLISECOND, @T, SYSDATETIME()) / 1000.0 AS DECIMAL(10, 2)
    ) AS VARCHAR(20)
) + ' seg';
SET @T = SYSDATETIME();

SELECT
    I.NAME AS INDICE,
    OBJECT_NAME(I.OBJECT_ID) AS TABLA
INTO #INDICES
FROM SYS.INDEXES AS I
WHERE
    I.OBJECT_ID IN (OBJECT_ID('FACTURA'), OBJECT_ID('DETALLE_FACTURA'))
    AND I.TYPE = 2
    AND I.IS_UNIQUE = 0
    AND I.IS_PRIMARY_KEY = 0
    AND I.IS_UNIQUE_CONSTRAINT = 0
    AND I.IS_DISABLED = 0;

SELECT
    @SQL = STRING_AGG(
        CAST(
            'ALTER INDEX ' + QUOTENAME(INDICE) + ' ON ' + QUOTENAME(TABLA)
            + ' DISABLE;' AS NVARCHAR(MAX)
        ), ' '
    )
FROM #INDICES;

IF @SQL IS NOT NULL
    EXEC SP_EXECUTESQL @SQL;

DECLARE @F_ID VARCHAR(50);
DECLARE @F_FECHA DATE;
DECLARE @F_EMP INT;
DECLARE @F_CLI INT;
DECLARE @F_MON CHAR(3);
DECLARE @F_TIPO VARCHAR(10);
DECLARE @F_EST VARCHAR(10);
DECLARE @F_SUB DECIMAL(18, 2);
DECLARE @F_DESC DECIMAL(18, 2);
DECLARE @F_IMP DECIMAL(18, 2);
DECLARE @F_MONTO DECIMAL(18, 2);

DECLARE CUR_FACTURAS CURSOR LOCAL FAST_FORWARD FOR
SELECT  -- noqa: ST06
    IDENTIFICADOR,
    CAST(FECHA_HORA AS DATE) AS FECHA_EMISION,
    ID_EMPRESA,
    ID_CLIENTE,
    COD_MONEDA,
    COD_TIPO,
    COD_ESTADO,
    SUBTOTAL,
    TOTAL_DESCUENTOS,
    IMPUESTOS_APLICADOS,
    MONTO_TOTAL
FROM #FACT
ORDER BY N;

OPEN CUR_FACTURAS;
FETCH NEXT FROM CUR_FACTURAS INTO
@F_ID, @F_FECHA, @F_EMP, @F_CLI, @F_MON,
@F_TIPO, @F_EST, @F_SUB, @F_DESC, @F_IMP, @F_MONTO;

SET @CONTADOR = 0;
BEGIN TRANSACTION;

WHILE @@FETCH_STATUS = 0 AND @COD = 0
    BEGIN
        EXEC USP_CREAR_FACTURA_SIN_FILTRO
            @ID_EMPRESA = @F_EMP,
            @ID_CLIENTE = @F_CLI,
            @COD_MONEDA = @F_MON,
            @COD_TIPO = @F_TIPO,
            @COD_ESTADO = @F_EST,
            @FECHA_EMISION = @F_FECHA,
            @SUBTOTAL = @F_SUB,
            @TOTAL_DESCUENTOS = @F_DESC,
            @IMPUESTOS_APLICADOS = @F_IMP,
            @MONTO_TOTAL = @F_MONTO,
            @IDENTIFICADOR = @F_ID OUTPUT,
            @CODIGO_ERROR = @COD OUTPUT,
            @MENSAJE = @MSG OUTPUT;

        SET @CONTADOR = @CONTADOR + 1;

        IF @COD = 0 AND @CONTADOR % @LOTE = 0
            BEGIN
                COMMIT TRANSACTION;
                BEGIN TRANSACTION;
            END;

        FETCH NEXT FROM CUR_FACTURAS INTO
        @F_ID, @F_FECHA, @F_EMP, @F_CLI, @F_MON,
        @F_TIPO, @F_EST, @F_SUB, @F_DESC, @F_IMP, @F_MONTO;
    END;

CLOSE CUR_FACTURAS;
DEALLOCATE CUR_FACTURAS;

IF @COD = 0
    COMMIT TRANSACTION;
ELSE IF @@TRANCOUNT > 0
    ROLLBACK TRANSACTION;

PRINT 'Facturas -> codigo ' + CAST(@COD AS VARCHAR(20))
+ ' (llamadas: ' + CAST(@CONTADOR AS VARCHAR(20)) + ')';
IF @COD <> 0
    PRINT 'Error: ' + @MSG;
PRINT 'Tiempo facturas: ' + CAST(
    CAST(
        DATEDIFF(MILLISECOND, @T, SYSDATETIME()) / 1000.0 AS DECIMAL(10, 2)
    ) AS VARCHAR(20)
) + ' seg';
SET @T = SYSDATETIME();

IF @COD = 0
    BEGIN
        DECLARE @D_ID VARCHAR(50);
        DECLARE @D_CORR INT;
        DECLARE @D_DESC NVARCHAR(255);
        DECLARE @D_CANT DECIMAL(18, 2);
        DECLARE @D_PRECIO DECIMAL(18, 2);
        DECLARE @D_IMP DECIMAL(5, 2);
        DECLARE @D_PROD INT;

        DECLARE CUR_DETALLES CURSOR LOCAL FAST_FORWARD FOR
        SELECT
            IDENTIFICADOR,
            NUMERO_CORRELATIVO,
            DESCRIPCION,
            CANTIDAD,
            PRECIO_UNITARIO,
            PORCENTAJE_IMPUESTO,
            ID_PRODUCTO
        FROM #DET
        ORDER BY N, NUMERO_CORRELATIVO;

        OPEN CUR_DETALLES;
        FETCH NEXT FROM CUR_DETALLES INTO
        @D_ID, @D_CORR, @D_DESC, @D_CANT, @D_PRECIO, @D_IMP, @D_PROD;

        SET @CONTADOR = 0;
        BEGIN TRANSACTION;

        WHILE @@FETCH_STATUS = 0 AND @COD = 0
            BEGIN
                EXEC USP_CREAR_DETALLE_FACTURA_SIN_FILTRO
                    @IDENTIFICADOR_FACTURA = @D_ID,
                    @NUMERO_CORRELATIVO = @D_CORR,
                    @DESCRIPCION = @D_DESC,
                    @CANTIDAD = @D_CANT,
                    @PRECIO_UNITARIO = @D_PRECIO,
                    @PORCENTAJE_IMPUESTO = @D_IMP,
                    @ID_PRODUCTO = @D_PROD,
                    @CODIGO_ERROR = @COD OUTPUT,
                    @MENSAJE = @MSG OUTPUT;

                SET @CONTADOR = @CONTADOR + 1;

                IF @COD = 0 AND @CONTADOR % @LOTE = 0
                    BEGIN
                        COMMIT TRANSACTION;
                        BEGIN TRANSACTION;
                    END;

                FETCH NEXT FROM CUR_DETALLES INTO
                @D_ID, @D_CORR, @D_DESC, @D_CANT, @D_PRECIO, @D_IMP, @D_PROD;
            END;

        CLOSE CUR_DETALLES;
        DEALLOCATE CUR_DETALLES;

        IF @COD = 0
            COMMIT TRANSACTION;
        ELSE IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        PRINT 'Detalles -> codigo ' + CAST(@COD AS VARCHAR(20))
        + ' (llamadas: ' + CAST(@CONTADOR AS VARCHAR(20)) + ')';
        IF @COD <> 0
            PRINT 'Error: ' + @MSG;
        PRINT 'Tiempo detalles: ' + CAST(
            CAST(
                DATEDIFF(MILLISECOND, @T, SYSDATETIME())
                / 1000.0 AS DECIMAL(10, 2)
            ) AS VARCHAR(20)
        ) + ' seg';
    END;

SET @T = SYSDATETIME();
SET @SQL = NULL;

SELECT
    @SQL = STRING_AGG(
        CAST(
            'ALTER INDEX ' + QUOTENAME(INDICE) + ' ON ' + QUOTENAME(TABLA)
            + ' REBUILD;' AS NVARCHAR(MAX)
        ), ' '
    )
FROM #INDICES;

IF @SQL IS NOT NULL
    BEGIN
        EXEC SP_EXECUTESQL @SQL;
        PRINT 'Indices reconstruidos: ' + CAST(
            CAST(
                DATEDIFF(MILLISECOND, @T, SYSDATETIME())
                / 1000.0 AS DECIMAL(10, 2)
            ) AS VARCHAR(20)
        ) + ' seg';
    END;

PRINT 'TIEMPO TOTAL: ' + CAST(
    CAST(
        DATEDIFF(MILLISECOND, @T_TOTAL, SYSDATETIME())
        / 1000.0 AS DECIMAL(10, 2)
    ) AS VARCHAR(20)
) + ' seg';
GO

CREATE OR ALTER PROCEDURE DBO.PR_MIGRAR_CLIENTE_JURIDICO
    @CEDULA VARCHAR(20),
    @RAZONSOCIAL VARCHAR(100),
    @NOMBRECOMERCIAL VARCHAR(100) = NULL,
    @CORREOELECTRONICO VARCHAR(100),
    @TELEFONO VARCHAR(20),
    @IDDIRECCION INT,
    @IDCLIENTEGENERADO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO CLIENTE_JURIDICO (
        CEDULA, RAZON_SOCIAL, NOMBRE_COMERCIAL, CORREO_ELECTRONICO, 
        TELEFONO, FECHA_REGISTRO, ULTIMA_ACTUALIZACION, ID_DIRECCION
    )
    VALUES (
        TRIM(@CEDULA), TRIM(@RAZONSOCIAL), ISNULL(NULLIF(TRIM(@NOMBRECOMERCIAL), ''), NULL),
        LOWER(TRIM(@CORREOELECTRONICO)), TRIM(@TELEFONO),
        GETDATE(), GETDATE(), @IDDIRECCION
    );
    SET @IDCLIENTEGENERADO = SCOPE_IDENTITY();
END;
GO

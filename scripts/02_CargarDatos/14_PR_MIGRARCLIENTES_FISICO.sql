CREATE OR ALTER PROCEDURE DBO.PR_MIGRAR_CLIENTE_FISICO
    @CEDULA VARCHAR(20),
    @NOMBRE VARCHAR(50),
    @APELLIDO1 VARCHAR(50),
    @APELLIDO2 VARCHAR(50) = NULL,
    @CORREOELECTRONICO VARCHAR(100),
    @TELEFONO VARCHAR(20),
    @IDDIRECCION INT,
    @IDCLIENTEGENERADO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO CLIENTE_FISICO (
        CEDULA, NOMBRE, APELLIDO1, APELLIDO2, CORREO_ELECTRONICO, 
        TELEFONO, FECHA_REGISTRO, ULTIMA_ACTUALIZACION, ID_DIRECCION
    )
    VALUES (
        TRIM(@CEDULA), TRIM(@NOMBRE), TRIM(@APELLIDO1), 
        ISNULL(NULLIF(TRIM(@APELLIDO2), ''), NULL),
        LOWER(TRIM(@CORREOELECTRONICO)), TRIM(@TELEFONO),
        GETDATE(), GETDATE(), @IDDIRECCION
    );

    SET @IDCLIENTEGENERADO = SCOPE_IDENTITY();
END;
GO

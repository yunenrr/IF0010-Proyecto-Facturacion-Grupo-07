USE SISTEMADEFACTURACION;
GO

CREATE OR ALTER PROCEDURE USP_CREAR_DETALLE_FACTURA_SIN_FILTRO (
    @IDENTIFICADOR_FACTURA VARCHAR(50),
    @NUMERO_CORRELATIVO INT,
    @DESCRIPCION NVARCHAR(255),
    @CANTIDAD DECIMAL(18, 2),
    @PRECIO_UNITARIO DECIMAL(18, 2),
    @PORCENTAJE_IMPUESTO DECIMAL(5, 2),
    @ID_PRODUCTO INT = NULL,
    @ID_SERVICIO INT = NULL,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE VARCHAR(500) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @SUBTOTAL DECIMAL(18, 2);
    DECLARE @TOTAL DECIMAL(18, 2);

    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = 'Detalle creado correctamente';

    -- Calculos de la linea
    SET @SUBTOTAL = @CANTIDAD * @PRECIO_UNITARIO;
    SET @TOTAL = @SUBTOTAL + (@SUBTOTAL * @PORCENTAJE_IMPUESTO / 100);

    -- Proceso
    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO DETALLE_FACTURA (
            IDENTIFICADOR_FACTURA,
            NUMERO_CORRELATIVO,
            DESCRIPCION,
            CANTIDAD,
            PRECIO_UNITARIO,
            PORCENTAJE_IMPUESTO,
            SUBTOTAL_LINEA,
            MONTOTOTAL_LINEA,
            ID_PRODUCTO,
            ID_SERVICIO
        )
        VALUES (
            @IDENTIFICADOR_FACTURA,
            @NUMERO_CORRELATIVO,
            @DESCRIPCION,
            @CANTIDAD,
            @PRECIO_UNITARIO,
            @PORCENTAJE_IMPUESTO,
            @SUBTOTAL,
            @TOTAL,
            @ID_PRODUCTO,
            @ID_SERVICIO
        );

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        -- si algo falla se deshace todo
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO

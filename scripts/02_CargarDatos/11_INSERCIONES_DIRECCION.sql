WITH 
    N0 AS (SELECT 1 AS c UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1 UNION ALL SELECT 1), -- 10
    N1 AS (SELECT 1 AS c FROM N0 a, N0 b),
    N2 AS (SELECT 1 AS c FROM N1 a, N1 b),
    N3 AS (SELECT 1 AS c FROM N2 a, N0 b),
    Numeros AS (
        SELECT TOP 50000 ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS N
        FROM N3
    )

INSERT INTO DIRECCION (DIRECCION_EXACTA, ID_DISTRITO)
SELECT 
    CONCAT('Calle ', N, ', Ave Central, Edificio Corporativo #', N) AS DIRECCION_EXACTA,
    10101 + (N % 5) AS ID_DISTRITO
FROM Numeros;

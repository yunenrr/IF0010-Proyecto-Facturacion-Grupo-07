SET NOCOUNT ON;

DECLARE @T_TOTAL DATETIME2 = SYSDATETIME();
DECLARE @T DATETIME2 = SYSDATETIME();
DECLARE @CANT_FACTURAS INT = 500000;
DECLARE @LOTE INT = 50000;
DECLARE @COD INT = 0;
DECLARE @MSG VARCHAR(500) = '';
DECLARE @CONTADOR INT;
DECLARE @SQL NVARCHAR(MAX);
DECLARE @SEG DECIMAL(10, 2);
DECLARE @LOG VARCHAR(200);

DROP TABLE IF EXISTS #EMPRESAS;
DROP TABLE IF EXISTS #CLIENTES;
DROP TABLE IF EXISTS #MONEDAS;
DROP TABLE IF EXISTS #TIPOS;
DROP TABLE IF EXISTS #ITEMS;
DROP TABLE IF EXISTS #BASE;
DROP TABLE IF EXISTS #FACT;
DROP TABLE IF EXISTS #DET;
DROP TABLE IF EXISTS #INDICES;

SELECT
    CAST(ROW_NUMBER() OVER (ORDER BY ID_EMPRESA) AS INT) AS N,
    ID_EMPRESA
INTO #EMPRESAS
FROM EMPRESA_EMISORA
WHERE INDICADOR = 1;

-- Unimos los dos tipos de clientes en una sola temporal
SELECT
    CAST(
        ROW_NUMBER() OVER (
            ORDER BY ID_CLIENTE_FISICO, ID_CLIENTE_JURIDICO
        ) AS INT
    ) AS N,
    ID_CLIENTE_FISICO,
    ID_CLIENTE_JURIDICO
INTO #CLIENTES
FROM (
    SELECT
        ID_CLIENTE AS ID_CLIENTE_FISICO,
        NULL AS ID_CLIENTE_JURIDICO
    FROM CLIENTE_FISICO

    UNION ALL

    SELECT
        NULL AS ID_CLIENTE_FISICO,
        ID_CLIENTE AS ID_CLIENTE_JURIDICO
    FROM CLIENTE_JURIDICO
) AS CLIENTES_UNIFICADOS;

SELECT
    CAST(
        ROW_NUMBER() OVER (ORDER BY COD_IDENTIFICADOR) AS INT
    ) AS N,
    COD_IDENTIFICADOR AS COD_MONEDA
INTO #MONEDAS
FROM MONEDAS;

SELECT
    CAST(
        ROW_NUMBER() OVER (ORDER BY COD_IDENTIFICADOR) AS INT
    ) AS N,
    COD_IDENTIFICADOR AS COD_TIPO
INTO #TIPOS
FROM TIPO_DOCUMENTO;

WITH P AS (
    SELECT TOP (3)
        CAST(
            ROW_NUMBER() OVER (ORDER BY ID_PRODUCTO) AS INT
        ) AS NUMERO_CORRELATIVO,
        ID_PRODUCTO,
        DESCRIPCION,
        PRECIO_UNITARIO,
        PORCENTAJE_IMPUESTO
    FROM PRODUCTOS
    WHERE ESTADO = 1
    ORDER BY ID_PRODUCTO
),

S AS (
    SELECT TOP (3)
        CAST(
            ROW_NUMBER() OVER (ORDER BY ID_SERVICIO) AS INT
        ) AS N,
        ID_SERVICIO
    FROM SERVICIOS
    WHERE ESTADO = 1
    ORDER BY ID_SERVICIO
)

SELECT
    P.NUMERO_CORRELATIVO,
    P.ID_PRODUCTO,
    S.ID_SERVICIO,
    P.DESCRIPCION,
    P.PRECIO_UNITARIO,
    P.PORCENTAJE_IMPUESTO,
    CAST(P.NUMERO_CORRELATIVO AS DECIMAL(18, 2)) AS CANTIDAD
INTO #ITEMS
FROM P
INNER JOIN S
    ON P.NUMERO_CORRELATIVO = S.N;

DECLARE @N_EMPRESAS INT;
DECLARE @N_CLIENTES INT;
DECLARE @N_MONEDAS INT;
DECLARE @N_TIPOS INT;
DECLARE @N_ITEMS INT;

SELECT @N_EMPRESAS = COUNT(*) FROM #EMPRESAS;
SELECT @N_CLIENTES = COUNT(*) FROM #CLIENTES;
SELECT @N_MONEDAS = COUNT(*) FROM #MONEDAS;
SELECT @N_TIPOS = COUNT(*) FROM #TIPOS;
SELECT @N_ITEMS = COUNT(*) FROM #ITEMS;

IF EXISTS (SELECT 1 FROM FACTURA)
    BEGIN
        RAISERROR (
            'Ya existen facturas. Ejecute limpiar_facturas.sql primero.',
            16,
            1
        );
        RETURN;
    END;

IF @N_EMPRESAS = 0 OR @N_CLIENTES = 0 OR @N_MONEDAS = 0 OR @N_TIPOS = 0
    BEGIN
        RAISERROR (
            'Faltan datos maestros (empresas, clientes, monedas o tipos).',
            16,
            1
        );
        RETURN;
    END;

IF @N_ITEMS < 3
    BEGIN
        RAISERROR (
            'Se necesitan al menos 3 productos y 3 servicios activos.',
            16,
            1
        );
        RETURN;
    END;

DECLARE @COUNT_ESTADOS INT;

SELECT @COUNT_ESTADOS = COUNT(*)
FROM ESTADO_FACTURA
WHERE ESTADO IN ('BORRADOR', 'EMITIDA', 'PAGADA', 'CANCELADA');

IF @COUNT_ESTADOS < 4
    BEGIN
        RAISERROR (
            'Faltan estados en ESTADO_FACTURA (BORRADOR, EMITIDA, PAGADA).',
            16,
            1
        );
        RETURN;
    END;

DECLARE @AHORA DATETIME = GETDATE();
DECLARE @INICIO DATETIME = DATEADD(YEAR, -1, @AHORA);
DECLARE @PASO INT = DATEDIFF(SECOND, @INICIO, @AHORA) / @CANT_FACTURAS;

IF @PASO < 1
    SET @PASO = 1;

SELECT TOP (@CANT_FACTURAS)
    CAST(ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS INT) AS N,
    (CHECKSUM(NEWID()) & 2147483647) AS R_EMPRESA,
    (CHECKSUM(NEWID()) & 2147483647) AS R_CLIENTE,
    (CHECKSUM(NEWID()) & 2147483647) AS R_MONEDA,
    (CHECKSUM(NEWID()) & 2147483647) AS R_TIPO,
    (CHECKSUM(NEWID()) & 2147483647) % 100 AS R_ESTADO,
    (CHECKSUM(NEWID()) & 2147483647) % @PASO AS SEGUNDOS_EXTRA,
    (CHECKSUM(NEWID()) & 2147483647) % 99001 AS R_SUBTOTAL,
    (CHECKSUM(NEWID()) & 2147483647) % 21 AS R_DESCUENTO
INTO #BASE
FROM SYS.ALL_OBJECTS AS A
CROSS JOIN SYS.ALL_OBJECTS AS B;

-- Los cálculos se hacen en CTEs encadenadas (en lugar de CROSS APPLY)
WITH TIEMPOS AS (
    SELECT
        N,
        R_EMPRESA,
        R_CLIENTE,
        R_MONEDA,
        R_TIPO,
        R_ESTADO,
        R_DESCUENTO,
        CAST(10 + R_SUBTOTAL / 100.0 AS DECIMAL(18, 2)) AS SUBTOTAL,
        DATEADD(SECOND, (N - 1) * @PASO + SEGUNDOS_EXTRA, @INICIO) AS TS
    FROM #BASE
),

DESCUENTOS AS (
    SELECT
        N,
        R_EMPRESA,
        R_CLIENTE,
        R_MONEDA,
        R_TIPO,
        R_ESTADO,
        TS,
        SUBTOTAL,
        CAST(SUBTOTAL * R_DESCUENTO / 100 AS DECIMAL(18, 2)) AS DESCUENTO
    FROM TIEMPOS
),

MONTOS AS (
    SELECT
        N,
        R_EMPRESA,
        R_CLIENTE,
        R_MONEDA,
        R_TIPO,
        R_ESTADO,
        TS,
        SUBTOTAL,
        DESCUENTO,
        CAST((SUBTOTAL - DESCUENTO) * 13 / 100 AS DECIMAL(18, 2)) AS IMPUESTO
    FROM DESCUENTOS
)

SELECT
    V.N,
    V.TS AS FECHA_HORA,
    EM.ID_EMPRESA,
    CL.ID_CLIENTE_FISICO,
    CL.ID_CLIENTE_JURIDICO,
    MO.COD_MONEDA,
    TI.COD_TIPO,
    E.COD_IDENTIFICADOR AS COD_ESTADO,
    V.SUBTOTAL,
    V.DESCUENTO AS TOTAL_DESCUENTOS,
    V.IMPUESTO AS IMPUESTOS_APLICADOS,
    CAST(NULL AS INT) AS ID_FACTURA,
    CAST(
        V.SUBTOTAL - V.DESCUENTO + V.IMPUESTO
        AS DECIMAL(18, 2)
    ) AS MONTO_TOTAL,
    CONVERT(CHAR(8), V.TS, 112)
    + REPLACE(CONVERT(CHAR(8), V.TS, 108), ':', '')
    + '-' + TI.COD_TIPO AS IDENTIFICADOR_COMPROBANTE
INTO #FACT
FROM MONTOS AS V
INNER JOIN #EMPRESAS AS EM
    ON EM.N = (V.R_EMPRESA % @N_EMPRESAS) + 1
INNER JOIN #CLIENTES AS CL
    ON CL.N = (V.R_CLIENTE % @N_CLIENTES) + 1
INNER JOIN #MONEDAS AS MO
    ON MO.N = (V.R_MONEDA % @N_MONEDAS) + 1
INNER JOIN #TIPOS AS TI
    ON TI.N = (V.R_TIPO % @N_TIPOS) + 1
INNER JOIN ESTADO_FACTURA AS E
    ON E.ESTADO = CASE
        WHEN V.R_ESTADO < 5 THEN 'BORRADOR'
        WHEN V.R_ESTADO < 35 THEN 'EMITIDA'
        WHEN V.R_ESTADO < 90 THEN 'PAGADA'
        ELSE 'CANCELADA'
    END;

CREATE CLUSTERED INDEX IX_FACT_N ON #FACT (N);

-- DESACTIVAR INDICES
SELECT
    I.NAME AS INDICE,
    OBJECT_NAME(I.OBJECT_ID) AS TABLA
INTO #INDICES
FROM SYS.INDEXES AS I
WHERE
    I.OBJECT_ID IN (
        OBJECT_ID('FACTURA'),
        OBJECT_ID('DETALLE_FACTURA')
    )
    AND I.TYPE = 2
    AND I.IS_UNIQUE = 0
    AND I.IS_PRIMARY_KEY = 0
    AND I.IS_UNIQUE_CONSTRAINT = 0
    AND I.IS_DISABLED = 0;

SELECT
    @SQL = STRING_AGG(
        CAST(
            CONCAT(
                'ALTER INDEX ', QUOTENAME(INDICE),
                ' ON ', QUOTENAME(TABLA), ' DISABLE;'
            ) AS NVARCHAR(MAX)
        ),
        ' '
    )
FROM #INDICES;

IF @SQL IS NOT NULL
    EXEC SP_EXECUTESQL @SQL;

DECLARE @F_ID INT;
DECLARE @F_N INT;
DECLARE @F_COMP VARCHAR(50);
DECLARE @F_FECHA DATE;
DECLARE @F_EMP INT;
DECLARE @F_CLI_FIS INT;
DECLARE @F_CLI_JUR INT;
DECLARE @F_MON CHAR(3);
DECLARE @F_TIPO VARCHAR(10);
DECLARE @F_EST VARCHAR(10);
DECLARE @F_SUB DECIMAL(18, 2);
DECLARE @F_DESC DECIMAL(18, 2);
DECLARE @F_IMP DECIMAL(18, 2);
DECLARE @F_MONTO DECIMAL(18, 2);

DECLARE CUR_FACTURAS CURSOR LOCAL FAST_FORWARD FOR
SELECT
    N,
    IDENTIFICADOR_COMPROBANTE,
    CAST(FECHA_HORA AS DATE) AS FECHA_EMISION,
    ID_EMPRESA,
    ID_CLIENTE_FISICO,
    ID_CLIENTE_JURIDICO,
    COD_MONEDA,
    COD_TIPO,
    COD_ESTADO,
    SUBTOTAL,
    TOTAL_DESCUENTOS,
    IMPUESTOS_APLICADOS,
    MONTO_TOTAL
FROM #FACT
ORDER BY N;

OPEN CUR_FACTURAS;
FETCH NEXT FROM CUR_FACTURAS INTO
@F_N, @F_COMP, @F_FECHA, @F_EMP, @F_CLI_FIS, @F_CLI_JUR, @F_MON,
@F_TIPO, @F_EST, @F_SUB, @F_DESC, @F_IMP, @F_MONTO;

SET @CONTADOR = 0;
BEGIN TRANSACTION;

WHILE @@FETCH_STATUS = 0 AND @COD = 0
    BEGIN
        EXEC USP_CREAR_FACTURA_SIN_FILTRO
            @ID_EMPRESA = @F_EMP,
            @ID_CLIENTE_FISICO = @F_CLI_FIS,
            @ID_CLIENTE_JURIDICO = @F_CLI_JUR,
            @COD_MONEDA = @F_MON,
            @COD_TIPO = @F_TIPO,
            @COD_ESTADO = @F_EST,
            @IDENTIFICADOR_COMPROBANTE = @F_COMP,
            @FECHA_EMISION = @F_FECHA,
            @SUBTOTAL = @F_SUB,
            @TOTAL_DESCUENTOS = @F_DESC,
            @IMPUESTOS_APLICADOS = @F_IMP,
            @MONTO_TOTAL = @F_MONTO,
            @IDENTIFICADOR = @F_ID OUTPUT,
            @CODIGO_ERROR = @COD OUTPUT,
            @MENSAJE = @MSG OUTPUT;

        IF @COD = 0
            BEGIN
                UPDATE #FACT
                SET ID_FACTURA = @F_ID
                WHERE N = @F_N;
            END;

        SET @CONTADOR = @CONTADOR + 1;

        IF @COD = 0 AND @CONTADOR % @LOTE = 0
            BEGIN
                COMMIT TRANSACTION;
                BEGIN TRANSACTION;
            END;

        FETCH NEXT FROM CUR_FACTURAS INTO
        @F_N, @F_COMP, @F_FECHA, @F_EMP, @F_CLI_FIS, @F_CLI_JUR, @F_MON,
        @F_TIPO, @F_EST, @F_SUB, @F_DESC, @F_IMP, @F_MONTO;
    END;

CLOSE CUR_FACTURAS;
DEALLOCATE CUR_FACTURAS;

IF @COD = 0
    COMMIT TRANSACTION;
ELSE IF @@TRANCOUNT > 0
    ROLLBACK TRANSACTION;

SET @LOG = 'Facturas -> codigo ' + CAST(@COD AS VARCHAR(20));
SET @LOG = @LOG + ' (llamadas: ';
SET @LOG = @LOG + CAST(@CONTADOR AS VARCHAR(20)) + ')';
PRINT @LOG;

IF @COD <> 0
    PRINT 'Error: ' + @MSG;

SET @SEG = DATEDIFF(MILLISECOND, @T, SYSDATETIME()) / 1000.0;
PRINT 'Tiempo facturas: ' + CAST(@SEG AS VARCHAR(20)) + ' seg';
SET @T = SYSDATETIME();

IF @COD = 0
    BEGIN
        SELECT
            F.ID_FACTURA,
            F.N,
            I.NUMERO_CORRELATIVO,
            I.DESCRIPCION,
            I.CANTIDAD,
            I.PRECIO_UNITARIO,
            I.PORCENTAJE_IMPUESTO,
            I.ID_PRODUCTO,
            I.ID_SERVICIO
        INTO #DET
        FROM #FACT AS F
        CROSS JOIN #ITEMS AS I
        WHERE F.ID_FACTURA IS NOT NULL;

        DECLARE @D_ID INT;
        DECLARE @D_CORR INT;
        DECLARE @D_DESC NVARCHAR(255);
        DECLARE @D_CANT DECIMAL(18, 2);
        DECLARE @D_PRECIO DECIMAL(18, 2);
        DECLARE @D_IMP DECIMAL(5, 2);
        DECLARE @D_PROD INT;
        DECLARE @D_SERV INT;

        DECLARE CUR_DETALLES CURSOR LOCAL FAST_FORWARD FOR
        SELECT
            ID_FACTURA,
            NUMERO_CORRELATIVO,
            DESCRIPCION,
            CANTIDAD,
            PRECIO_UNITARIO,
            PORCENTAJE_IMPUESTO,
            ID_PRODUCTO,
            ID_SERVICIO
        FROM #DET
        ORDER BY N, NUMERO_CORRELATIVO;

        OPEN CUR_DETALLES;
        FETCH NEXT FROM CUR_DETALLES INTO
        @D_ID, @D_CORR, @D_DESC, @D_CANT,
        @D_PRECIO, @D_IMP, @D_PROD, @D_SERV;

        SET @CONTADOR = 0;
        BEGIN TRANSACTION;

        WHILE @@FETCH_STATUS = 0 AND @COD = 0
            BEGIN
                EXEC USP_CREAR_DETALLE_FACTURA_SIN_FILTRO
                    @IDENTIFICADOR_FACTURA = @D_ID,
                    @NUMERO_CORRELATIVO = @D_CORR,
                    @DESCRIPCION = @D_DESC,
                    @CANTIDAD = @D_CANT,
                    @PRECIO_UNITARIO = @D_PRECIO,
                    @PORCENTAJE_IMPUESTO = @D_IMP,
                    @ID_PRODUCTO = @D_PROD,
                    @ID_SERVICIO = @D_SERV,
                    @CODIGO_ERROR = @COD OUTPUT,
                    @MENSAJE = @MSG OUTPUT;

                SET @CONTADOR = @CONTADOR + 1;

                IF @COD = 0 AND @CONTADOR % @LOTE = 0
                    BEGIN
                        COMMIT TRANSACTION;
                        BEGIN TRANSACTION;
                    END;

                FETCH NEXT FROM CUR_DETALLES INTO
                @D_ID, @D_CORR, @D_DESC, @D_CANT,
                @D_PRECIO, @D_IMP, @D_PROD, @D_SERV;
            END;

        CLOSE CUR_DETALLES;
        DEALLOCATE CUR_DETALLES;

        IF @COD = 0
            COMMIT TRANSACTION;
        ELSE IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        SET @LOG = 'Detalles -> codigo ' + CAST(@COD AS VARCHAR(20));
        SET @LOG = @LOG + ' (llamadas: ';
        SET @LOG = @LOG + CAST(@CONTADOR AS VARCHAR(20)) + ')';
        PRINT @LOG;

        IF @COD <> 0
            PRINT 'Error: ' + @MSG;

        SET @SEG = DATEDIFF(MILLISECOND, @T, SYSDATETIME()) / 1000.0;
        PRINT 'Tiempo detalles: ' + CAST(@SEG AS VARCHAR(20)) + ' seg';
    END;

SET @T = SYSDATETIME();
SET @SQL = NULL;

SELECT
    @SQL = STRING_AGG(
        CAST(
            CONCAT(
                'ALTER INDEX ', QUOTENAME(INDICE),
                ' ON ', QUOTENAME(TABLA), ' REBUILD;'
            ) AS NVARCHAR(MAX)
        ),
        ' '
    )
FROM #INDICES;

IF @SQL IS NOT NULL
    BEGIN
        EXEC SP_EXECUTESQL @SQL;
        SET @SEG = DATEDIFF(MILLISECOND, @T, SYSDATETIME()) / 1000.0;
        PRINT 'Indices reconstruidos: ' + CAST(@SEG AS VARCHAR(20)) + ' seg';
    END;

SET @SEG = DATEDIFF(MILLISECOND, @T_TOTAL, SYSDATETIME()) / 1000.0;
PRINT 'TIEMPO TOTAL: ' + CAST(@SEG AS VARCHAR(20)) + ' seg';
GO

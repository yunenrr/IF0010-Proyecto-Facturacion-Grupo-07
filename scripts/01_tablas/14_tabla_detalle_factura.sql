USE SISTEMADEFACTURACION;

CREATE TABLE DETALLE_FACTURA (
    ID_DETALLE INT IDENTITY (1, 1) NOT NULL,
    IDENTIFICADOR_FACTURA VARCHAR(50) NOT NULL,
    NUMERO_CORRELATIVO INT NOT NULL,
    DESCRIPCION NVARCHAR(255) NOT NULL,
    CANTIDAD DECIMAL(18, 2) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL,
    SUBTOTAL_LINEA DECIMAL(18, 2) NOT NULL,
    MONTOTOTAL_LINEA DECIMAL(18, 2) NOT NULL,
    ID_PRODUCTO INT NULL,
    ID_SERVICIO INT NULL,
    CONSTRAINT PK_DETALLE_FACTURA PRIMARY KEY(
        IDENTIFICADOR_FACTURA,
        NUMERO_CORRELATIVO
    ),
    CONSTRAINT FK_DETALLE_FACTURA_ENCABEZADO
    FOREIGN KEY (IDENTIFICADOR_FACTURA)
    REFERENCES FACTURA (IDENTIFICADOR) ON DELETE CASCADE,
    
    CONSTRAINT FK_DETALLE_PRODUCTO
    FOREIGN KEY (ID_PRODUCTO)
    REFERENCES PRODUCTOS (ID_PRODUCTO),

    CONSTRAINT FK_DETALLE_SERVICIO
    FOREIGN KEY (ID_SERVICIO)
    REFERENCES SERVICIOS (ID_SERVICIO),

    CONSTRAINT CK_CANTIDAD_POSITIVA
        CHECK (CANTIDAD > 0),

    CONSTRAINT CK_PRECIO_POSITIVO
        CHECK (PRECIO_UNITARIO > 0),

    CONSTRAINT CK_IMPUESTO_NO_NEGATIVO
        CHECK (PORCENTAJE_IMPUESTO >= 0),

    CONSTRAINT CK_SUBTOTAL_NO_NEGATIVO
        CHECK (SUBTOTAL_LINEA >= 0),

    CONSTRAINT CK_MONTOTOTAL_NO_NEGATIVO
        CHECK (MONTOTOTAL_LINEA >= 0),

    CONSTRAINT CK_PRODUCTO_O_SERVICIO
        CHECK (
            (ID_PRODUCTO IS NOT NULL AND ID_SERVICIO IS NULL)
            OR
            (ID_PRODUCTO IS NULL AND ID_SERVICIO IS NOT NULL)
        )
);

USE SISTEMADEFACTURACION;

DROP TABLE IF EXISTS CLIENTE_JURIDICO;
GO
CREATE TABLE CLIENTE_JURIDICO (
    ID_CLIENTE INT IDENTITY (1, 1),
    CEDULA VARCHAR(20) NOT NULL,
    RAZON_SOCIAL VARCHAR(100) NOT NULL,
    NOMBRE_COMERCIAL VARCHAR(100) NULL,
    CORREO_ELECTRONICO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(20) NOT NULL,
    FECHA_REGISTRO DATE NOT NULL,
    ULTIMA_ACTUALIZACION DATE NOT NULL,
    ID_DIRECCION INT UNIQUE NOT NULL,
    CONSTRAINT PK_CLIENTE_JURIDICO PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_JURIDICO_CEDULA UNIQUE (CEDULA),
    CONSTRAINT UQ_CLIENTE_JURIDICO_DIRECCION UNIQUE (ID_DIRECCION),
    FOREIGN KEY (ID_DIRECCION) REFERENCES DIRECCION (ID_DIRECCION)
);

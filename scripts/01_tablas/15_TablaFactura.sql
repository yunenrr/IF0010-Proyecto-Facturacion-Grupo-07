USE SISTEMADEFACTURACION;

CREATE TABLE FACTURA (
    IDENTIFICADOR INT IDENTITY (1, 1) NOT NULL,
    IDENTIFICADOR_COMPROBANTE VARCHAR(50) NOT NULL,
    FECHA_EMISION DATE NOT NULL,
    SUBTOTAL DECIMAL(18, 2) NOT NULL,
    TOTAL_DESCUENTOS DECIMAL(18, 2) NOT NULL,
    IMPUESTOS_APLICADOS DECIMAL(18, 2) NOT NULL,
    MONTO_TOTAL DECIMAL(18, 2) NOT NULL,
    FECHA_CREACION DATETIME NOT NULL DEFAULT GETDATE(),
    MODIFICACION DATETIME NULL,
    OBSERVACIONES NVARCHAR(255) NULL,
    ID_EMPRESA INT NOT NULL,
    ID_CLIENTE_FISICO INT NULL,
    ID_CLIENTE_JURIDICO INT NULL,
    COD_IDENTIFICADOR_MONEDA CHAR(3) NOT NULL,
    COD_IDENTIFICADOR_TIPO VARCHAR(10) NOT NULL,
    COD_IDENTIFICADOR_ESTADO VARCHAR(10) NOT NULL,
    CONSTRAINT PK_FACTURA
    PRIMARY KEY (IDENTIFICADOR),
    CONSTRAINT UQ_FACTURA_COMPROBANTE
    UNIQUE (IDENTIFICADOR_COMPROBANTE),
    CONSTRAINT FK_FACTURA_EMPRESA
    FOREIGN KEY (ID_EMPRESA)
    REFERENCES EMPRESA_EMISORA (ID_EMPRESA),
    CONSTRAINT FK_FACTURA_CLIENTE_FISICO
    FOREIGN KEY (ID_CLIENTE_FISICO)
    REFERENCES CLIENTE_FISICO (ID_CLIENTE),
    CONSTRAINT FK_FACTURA_CLIENTE_JURIDICO
    FOREIGN KEY (ID_CLIENTE_JURIDICO)
    REFERENCES CLIENTE_JURIDICO (ID_CLIENTE),
    CONSTRAINT FK_FACTURA_MONEDA
    FOREIGN KEY (COD_IDENTIFICADOR_MONEDA)
    REFERENCES MONEDAS (COD_IDENTIFICADOR),
    CONSTRAINT FK_FACTURA_TIPO
    FOREIGN KEY (COD_IDENTIFICADOR_TIPO)
    REFERENCES TIPO_DOCUMENTO (COD_IDENTIFICADOR),
    CONSTRAINT FK_FACTURA_ESTADO
    FOREIGN KEY (COD_IDENTIFICADOR_ESTADO)
    REFERENCES ESTADO_FACTURA (COD_IDENTIFICADOR)
);

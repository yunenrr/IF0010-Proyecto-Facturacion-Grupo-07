USE SISTEMADEFACTURACION;

CREATE TABLE EMPRESA_EMISORA (
    ID_EMPRESA INT IDENTITY (1, 1),
    CEDULA VARCHAR(20) NOT NULL,
    NOMBRE_COMERCIAL VARCHAR(100) NOT NULL,
    RAZON_SOCIAL VARCHAR(100) NOT NULL,
    FECHA DATE NOT NULL,
    INDICADOR BIT
    CONSTRAINT DF_EMPRESA_EMISORA_INDICADOR DEFAULT 1 NOT NULL,
    CORREO_ELECTRONICO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(20) NOT NULL,
    ID_DIRECCION INT UNIQUE NOT NULL,
    CONSTRAINT PK_EMPRESA_EMISORA PRIMARY KEY (ID_EMPRESA),
    CONSTRAINT FK_EMPRESA_EMISORA_DIRECCION UNIQUE (ID_DIRECCION),
    FOREIGN KEY (ID_DIRECCION) REFERENCES DIRECCION (ID_DIRECCION)
);

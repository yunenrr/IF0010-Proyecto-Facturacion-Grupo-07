USE SISTEMADEFACTURACION;

DROP TABLE IF EXISTS CLIENTE_FISICO;

CREATE TABLE CLIENTE_FISICO (
    ID_CLIENTE INT IDENTITY (1, 1),
    CEDULA VARCHAR(20) NOT NULL,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO1 VARCHAR(50) NOT NULL,
    APELLIDO2 VARCHAR(50) NULL,
    CORREO_ELECTRONICO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(20) NOT NULL,
    FECHA_REGISTRO DATE NOT NULL,
    ULTIMA_ACTUALIZACION DATE NOT NULL,
    ID_DIRECCION INT UNIQUE NOT NULL,
    CONSTRAINT PK_CLIENTE_FISICO PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_FISICO_CEDULA UNIQUE (CEDULA),
    CONSTRAINT UQ_CLIENTE_FISICO_DIRECCION UNIQUE (ID_DIRECCION),
    FOREIGN KEY (ID_DIRECCION) REFERENCES DIRECCION (ID_DIRECCION)
);

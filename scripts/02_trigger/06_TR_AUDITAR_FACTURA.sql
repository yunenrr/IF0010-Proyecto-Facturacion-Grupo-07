USE SISTEMADEFACTURACION;
GO

CREATE OR ALTER TRIGGER DBO.TR_FACTURA_AUDITORIA
ON DBO.FACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ID_TABLA_AUDITADA INT;
    DECLARE @FILAS_INSERTADAS INT = (SELECT COUNT(*) FROM INSERTED);
    DECLARE @FILAS_ELIMINADAS INT = (SELECT COUNT(*) FROM DELETED);

    SELECT @ID_TABLA_AUDITADA = TA.ID_TABLA_AUDITADA
    FROM DBO.TABLA_AUDITADA AS TA
    WHERE TA.NOMBRE_TABLA = 'FACTURA';

    -- INSERT
    IF @FILAS_INSERTADAS > 0 AND @FILAS_ELIMINADAS = 0
        BEGIN
            INSERT INTO DBO.HISTORIAL (
                ID_TABLA_AUDITADA,
                REGISTRO_ID,
                OPERACION_REALIZADA,
                ESTADO_PREVIO,
                NUEVO_ESTADO,
                FECHA_CAMBIO,
                DESCRIPCION
            )
            SELECT
                @ID_TABLA_AUDITADA AS ID_TABLA_AUDITADA,
                I.IDENTIFICADOR AS REGISTRO_ID,
                'INSERT' AS OPERACION_REALIZADA,
                NULL AS ESTADO_PREVIO,
                CAST(I.MONTO_TOTAL AS VARCHAR(100)) AS NUEVO_ESTADO,
                GETDATE() AS FECHA_CAMBIO,
                'SE CREO UNA NUEVA FACTURA' AS DESCRIPCION
            FROM INSERTED AS I;
        END;

    -- UPDATE
    IF @FILAS_INSERTADAS > 0 AND @FILAS_ELIMINADAS > 0
        BEGIN
            INSERT INTO DBO.HISTORIAL (
                ID_TABLA_AUDITADA,
                REGISTRO_ID,
                OPERACION_REALIZADA,
                ESTADO_PREVIO,
                NUEVO_ESTADO,
                FECHA_CAMBIO,
                DESCRIPCION
            )
            SELECT
                @ID_TABLA_AUDITADA AS ID_TABLA_AUDITADA,
                I.IDENTIFICADOR AS REGISTRO_ID,
                'UPDATE' AS OPERACION_REALIZADA,
                CAST(D.MONTO_TOTAL AS VARCHAR(100)) AS ESTADO_PREVIO,
                CAST(I.MONTO_TOTAL AS VARCHAR(100)) AS NUEVO_ESTADO,
                GETDATE() AS FECHA_CAMBIO,
                'SE MODIFICO LA FACTURA' AS DESCRIPCION
            FROM INSERTED AS I
            INNER JOIN DELETED AS D
                ON I.IDENTIFICADOR = D.IDENTIFICADOR;
        END;

    -- DELETE
    IF @FILAS_ELIMINADAS > 0 AND @FILAS_INSERTADAS = 0
        BEGIN
            INSERT INTO DBO.HISTORIAL (
                ID_TABLA_AUDITADA,
                REGISTRO_ID,
                OPERACION_REALIZADA,
                ESTADO_PREVIO,
                NUEVO_ESTADO,
                FECHA_CAMBIO,
                DESCRIPCION
            )
            SELECT
                @ID_TABLA_AUDITADA AS ID_TABLA_AUDITADA,
                D.IDENTIFICADOR AS REGISTRO_ID,
                'DELETE' AS OPERACION_REALIZADA,
                CAST(D.MONTO_TOTAL AS VARCHAR(100)) AS ESTADO_PREVIO,
                NULL AS NUEVO_ESTADO,
                GETDATE() AS FECHA_CAMBIO,
                'SE ELIMINO LA FACTURA' AS DESCRIPCION
            FROM DELETED AS D;
        END;
END;
GO

CREATE OR ALTER FUNCTION DBO.FN_MONTO_FINAL_PAGAR(
    @IDENTIFICADOR_FACTURA INT
)
RETURNS DECIMAL(18, 2)
AS
BEGIN
    DECLARE @MONTO_FINAL DECIMAL(18, 2);

    SELECT
        @MONTO_FINAL = CAST(
            SUBTOTAL - TOTAL_DESCUENTOS + IMPUESTOS_APLICADOS
            AS DECIMAL(18, 2)
        )
    FROM DBO.FACTURA
    WHERE IDENTIFICADOR = @IDENTIFICADOR_FACTURA;

    RETURN @MONTO_FINAL;
END;
GO


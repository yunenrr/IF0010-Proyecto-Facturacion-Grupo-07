USE SISTEMADEFACTURACION;
GO

CREATE OR ALTER FUNCTION DBO.FN_CLAVE_COMPROBANTE(
    @FECHA DATETIME,
    @COD_TIPO VARCHAR(10)
)
RETURNS VARCHAR(50)
AS
BEGIN
    RETURN CONVERT(CHAR(8), @FECHA, 112)
    + REPLACE(CONVERT(CHAR(8), @FECHA, 108), ':', '')
    + '-' + TRIM(@COD_TIPO);
END;
GO

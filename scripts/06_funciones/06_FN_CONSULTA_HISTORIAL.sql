--CREACION DE LOGINS
USE MASTER;
GO

DECLARE @ClaveAuditor NVARCHAR(128) = N'Hola12345';
DECLARE @ClaveDBA NVARCHAR(128) = N'Hola123456';
DECLARE @ClaveConsulta NVARCHAR(128) = N'Hola1234567';

--CLAVES NO NULAS
IF
    @ClaveAuditor IS NULL OR @ClaveDBA IS NULL
    OR @ClaveConsulta IS NULL
    THROW 51001, 'Completar las tres claves.', 1;

--CLAVES NO VACIAS
IF
    TRIM(@ClaveAuditor) = ''
    OR TRIM(@ClaveDBA) = ''
    OR TRIM(@ClaveConsulta) = ''
    THROW 51002, 'Las claves no pueden estar vacías.', 1;

--CLAVES DIFERENTES
IF
    @ClaveAuditor = @ClaveDBA
    OR @ClaveAuditor = @ClaveConsulta
    OR @ClaveDBA = @ClaveConsulta
    THROW 51003, 'Las claves deben ser distintas.', 1;

--VERIFICAR QUE NO EXISTAN LOS LOGINS
IF
    EXISTS (
        SELECT 1
        FROM SYS.SERVER_PRINCIPALS
        WHERE NAME IN ('ProyectoAuditor', 'ProyectoDBA', 'ProyectoConsulta')
    )
    THROW 51004, 'Ya existe uno de los logins.', 1;

--CREAR LOS LOGINS
DECLARE @Comando NVARCHAR(MAX);

SET
    @Comando = N'CREATE LOGIN ProyectoAuditor WITH PASSWORD = '
    + QUOTENAME(@ClaveAuditor, '''')
    + N', CHECK_POLICY = ON, CHECK_EXPIRATION = ON;';
EXEC (@Comando);

SET
    @Comando = N'CREATE LOGIN ProyectoDBA WITH PASSWORD = '
    + QUOTENAME(@ClaveDBA, '''')
    + N', CHECK_POLICY = ON, CHECK_EXPIRATION = ON;';
EXEC (@Comando);

SET
    @Comando = N'CREATE LOGIN ProyectoConsulta WITH PASSWORD = '
    + QUOTENAME(@ClaveConsulta, '''')
    + N', CHECK_POLICY = ON, CHECK_EXPIRATION = ON;';
EXEC (@Comando);

--VERIFICAR LOGINS
SELECT
    NAME,
    IS_POLICY_CHECKED,
    IS_EXPIRATION_CHECKED
FROM SYS.SQL_LOGINS
WHERE NAME IN ('ProyectoAuditor', 'ProyectoDBA', 'ProyectoConsulta');
GO

USE SISTEMADEFACTURACION;
GO
--CREAR USUARIOS
CREATE USER AUDITORDEMO FOR LOGIN PROYECTOAUDITOR;
CREATE USER DBADEMO FOR LOGIN PROYECTODBA;
CREATE USER CONSULTADEMO FOR LOGIN PROYECTOCONSULTA;
GO

--CREACION DE ROLES
CREATE ROLE AUDITOR AUTHORIZATION DBO;
CREATE ROLE DBA AUTHORIZATION DBO;
GO

--ASIGNACION DE ROLES
ALTER ROLE AUDITOR ADD MEMBER AUDITORDEMO; -- noqa: PRS
ALTER ROLE DBA ADD MEMBER DBADEMO; -- noqa: PRS
GO

--FUNCION PARA HISTORIAL DE CAMBIOS
--CON ROL DE AUDITOR Y DBA
CREATE OR ALTER FUNCTION DBO.FN_CONSULTA_HISTORIAL()
RETURNS TABLE
AS
RETURN (
    SELECT
        H.ID_HISTORIAL,
        A.NOMBRE_TABLA,
        H.REGISTRO_ID,
        H.OPERACION_REALIZADA,
        H.ESTADO_PREVIO,
        H.NUEVO_ESTADO,
        H.FECHA_CAMBIO,
        H.DESCRIPCION

    FROM DBO.HISTORIAL AS H
    INNER JOIN DBO.TABLA_AUDITADA AS A
        ON H.ID_TABLA_AUDITADA = A.ID_TABLA_AUDITADA
    WHERE
        IS_MEMBER('AUDITOR') = 1
        OR IS_MEMBER('DBA') = 1
);
GO

--OTORGAR PERMISOS 
GRANT SELECT ON DBO.FN_CONSULTA_HISTORIAL TO AUDITOR;
GRANT SELECT ON DBO.FN_CONSULTA_HISTORIAL TO DBA;
GRANT SELECT ON DBO.FN_CONSULTA_HISTORIAL TO CONSULTADEMO;
GO

USE MASTER;
GO

DECLARE @CLAVE_ADMIN NVARCHAR(128) = N'AdminClave2026!';
DECLARE @CLAVE_OPERATIVO NVARCHAR(128) = N'OperativoClave2026!';

IF
   @CLAVE_ADMIN IS NULL
   OR @CLAVE_OPERATIVO IS NULL
      THROW 51005, 'Completar las claves.', 1;

IF 
   TRIM(@CLAVE_ADMIN) = '' 
   OR TRIM(@CLAVE_OPERATIVO) = ''
       THROW 50001, N'No pueden ir vacías', 1;

IF @CLAVE_ADMIN = @CLAVE_OPERATIVO
    THROW 51006, 'Usar claves distintas.', 1;

IF 
   EXISTS (
       SELECT 1
       FROM SYS.SERVER_PRINCIPALS
       WHERE NAME IN (N'LOGINADMINDEMO', N'LOGINOPERATIVODEMO')
   )
       THROW 51007, 'Ya existe un login del laboratorio; no se sobrescribe.', 1;

DECLARE @COMANDO NVARCHAR(MAX);

SET 
   @COMANDO = N'CREATE LOGIN LOGINADMINDEMO WITH PASSWORD = '
    + QUOTENAME(@CLAVE_ADMIN, '''')
    + N', CHECK_POLICY = ON, CHECK_EXPIRATION = ON;';
EXEC (@COMANDO);

SET 
   @COMANDO = N'CREATE LOGIN LOGINOPERATIVODEMO WITH PASSWORD = '
    + QUOTENAME(@CLAVE_OPERATIVO, '''')
    + N', CHECK_POLICY = ON, CHECK_EXPIRATION = ON;';
EXEC (@COMANDO);

USE SISTEMADEFACTURACION;
GO

DROP USER IF EXISTS ADMINDEMO;
DROP USER IF EXISTS OPERATIVODEMO;
GO

CREATE USER ADMINDEMO FOR LOGIN LOGINADMINDEMO;
CREATE USER OPERATIVODEMO FOR LOGIN LOGINOPERATIVODEMO;
GO

IF NOT EXISTS (
    SELECT * 
    FROM SYS.DATABASE_PRINCIPALS 
    WHERE NAME = N'ROLADMINISTRATIVO' 
      AND TYPE = 'R'
)
CREATE ROLE ROLADMINISTRATIVO AUTHORIZATION DBO;
GO

IF NOT EXISTS (
    SELECT * 
    FROM SYS.DATABASE_PRINCIPALS 
    WHERE NAME = N'ROLOPERATIVO' 
      AND TYPE = 'R'
)
CREATE ROLE ROLOPERATIVO AUTHORIZATION DBO;
GO

ALTER ROLE ROLADMINISTRATIVO ADD MEMBER ADMINDEMO;
ALTER ROLE ROLOPERATIVO ADD MEMBER OPERATIVODEMO;
GO

ALTER TABLE DBO.CLIENTE 
ALTER COLUMN CORREO_ELECTRONICO ADD MASKED WITH (FUNCTION = 'email()');

ALTER TABLE DBO.CLIENTE 
ALTER COLUMN TELEFONO ADD MASKED WITH (FUNCTION = 'partial(0,"XXXX",4)');
GO

GRANT SELECT ON DBO.CLIENTE TO ROLADMINISTRATIVO;
GRANT SELECT ON DBO.CLIENTE TO ROLOPERATIVO;
GRANT UNMASK ON DBO.CLIENTE TO ROLADMINISTRATIVO;
GO

IF OBJECT_ID(N'DBO.FN_CONSULTARCLIENTEPORCEDULA', N'IF') IS NOT NULL
    DROP FUNCTION DBO.FN_CONSULTARCLIENTEPORCEDULA;
GO

CREATE FUNCTION DBO.FN_CONSULTARCLIENTEPORCEDULA (
    @P_CEDULA VARCHAR(20)
)
RETURNS TABLE
AS
RETURN
(
    SELECT 
        C.ID_CLIENTE,
        C.CEDULA,
        C.NOMBRE_RAZON_SOCIAL,
        C.CORREO_ELECTRONICO,
        C.TELEFONO,
        C.FECHA_REGISTRO,
        C.ULTIMA_ACTUALIZACION,
        C.ID_DIRECCION
    FROM DBO.CLIENTE AS C
    WHERE C.CEDULA = @P_CEDULA
);
GO

GRANT SELECT ON DBO.FN_CONSULTARCLIENTEPORCEDULA TO ROLADMINISTRATIVO;
GRANT SELECT ON DBO.FN_CONSULTARCLIENTEPORCEDULA TO ROLOPERATIVO;
GO

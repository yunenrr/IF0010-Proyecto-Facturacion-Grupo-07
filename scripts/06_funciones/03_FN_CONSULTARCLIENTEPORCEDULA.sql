IF OBJECT_ID(N'DBO.FN_CONSULTARCLIENTEPORCEDULA', N'IF') IS NOT NULL
    DROP FUNCTION DBO.FN_CONSULTARCLIENTEPORCEDULA;
GO

CREATE FUNCTION DBO.FN_CONSULTARCLIENTEPORCEDULA(
    @P_CEDULA VARCHAR(20)
)
RETURNS TABLE
AS
RETURN
(
    -- Búsqueda en Cliente Físico
    SELECT
        CF.ID_CLIENTE,
        CF.CEDULA,
        CAST(
            CF.NOMBRE + ' ' + CF.APELLIDO1 + ' ' + ISNULL(CF.APELLIDO2, '')
            AS VARCHAR(100)
        ) AS NOMBRE_RAZON_SOCIAL,
        CF.CORREO_ELECTRONICO,
        CF.TELEFONO,
        CF.FECHA_REGISTRO,
        CF.ULTIMA_ACTUALIZACION,
        CF.ID_DIRECCION
    FROM DBO.CLIENTE_FISICO AS CF
    WHERE CF.CEDULA = @P_CEDULA

    UNION ALL

    -- Búsqueda en Cliente Jurídico
    SELECT
        CJ.ID_CLIENTE,
        CJ.CEDULA,
        CJ.RAZON_SOCIAL AS NOMBRE_RAZON_SOCIAL,
        CJ.CORREO_ELECTRONICO,
        CJ.TELEFONO,
        CJ.FECHA_REGISTRO,
        CJ.ULTIMA_ACTUALIZACION,
        CJ.ID_DIRECCION
    FROM DBO.CLIENTE_JURIDICO AS CJ
    WHERE CJ.CEDULA = @P_CEDULA
);
GO

GRANT SELECT ON DBO.FN_CONSULTARCLIENTEPORCEDULA TO ROLADMINISTRATIVO;
GRANT SELECT ON DBO.FN_CONSULTARCLIENTEPORCEDULA TO ROLOPERATIVO;
GO

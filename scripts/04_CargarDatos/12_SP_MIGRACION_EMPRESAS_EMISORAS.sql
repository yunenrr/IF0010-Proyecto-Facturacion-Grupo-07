USE SISTEMADEFACTURACION;
GO

IF EXISTS (
    SELECT 1
    FROM SYS.OBJECTS
    WHERE NAME = 'PR_MIGRAREMPRESASEMISORAS'
      AND TYPE = 'P'
)
BEGIN
    DROP PROCEDURE DBO.PR_MIGRAREMPRESASEMISORAS;
END;
GO

CREATE OR ALTER PROCEDURE DBO.PR_MIGRAREMPRESASEMISORAS
    @CEDULA VARCHAR(20),
    @NOMBRECOMERCIAL VARCHAR(100),
    @RAZONSOCIAL VARCHAR(100),
    @INDICADOR BIT = 1,
    @CORREOELECTRONICO VARCHAR(100),
    @TELEFONO VARCHAR(20),
    @IDDIRECCION INT,
    @IDEMPRESAGENERADO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO EMPRESA_EMISORA (
        CEDULA,
        NOMBRE_COMERCIAL,
        RAZON_SOCIAL,
        FECHA,
        INDICADOR,
        CORREO_ELECTRONICO,
        TELEFONO,
        ID_DIRECCION
    )
    VALUES (
        TRIM(@CEDULA),
        TRIM(@NOMBRECOMERCIAL),
        TRIM(@RAZONSOCIAL),
        GETDATE(),
        @INDICADOR,
        LOWER(TRIM(@CORREOELECTRONICO)),
        TRIM(@TELEFONO),
        @IDDIRECCION
    );

    SET @IDEMPRESAGENERADO = SCOPE_IDENTITY();
END;
GO

USE SISTEMADEFACTURACION;
GO

IF EXISTS (
    SELECT
        1
    FROM SYS.OBJECTS
    WHERE
        NAME = 'PR_MIGRARCLIENTES'
        AND TYPE = 'P'
)
BEGIN
    DROP PROCEDURE DBO.PR_MIGRARCLIENTES;
END;
GO

CREATE OR ALTER PROCEDURE DBO.PR_MIGRARCLIENTES
    @CEDULA VARCHAR(20),
    @NOMBRERAZONSOCIAL VARCHAR(100) = 'No aplica',
    @CORREOELECTRONICO VARCHAR(100),
    @TELEFONO VARCHAR(20),
    @IDDIRECCION INT,
    @IDCLIENTEGENERADO INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO CLIENTE (
        CEDULA,
        NOMBRE_RAZON_SOCIAL,
        CORREO_ELECTRONICO,
        TELEFONO,
        FECHA_REGISTRO,
        ULTIMA_ACTUALIZACION,
        ID_DIRECCION
    )
    VALUES (
        TRIM(@CEDULA),
        ISNULL(NULLIF(TRIM(@NOMBRERAZONSOCIAL), ''), 'No aplica'),
        LOWER(TRIM(@CORREOELECTRONICO)),
        TRIM(@TELEFONO),
        GETDATE(),
        GETDATE(),
        @IDDIRECCION
    );

    SET @IDCLIENTEGENERADO = SCOPE_IDENTITY();
END;
GO

--CONSULTA PARA VERIFICAR LA FUNCION DE HISTORIAL
--USUARIOS AUDITOR Y DBA PUEDEN VER EL HISTORIAL
--USUARIO CONSULTA ES DE PRUEBA PARA VERIFICAR QUE NO PUEDE VERLO
USE SISTEMADEFACTURACION;
GO

--VERIFICAR AUDITOR
EXECUTE AS USER = 'AuditorDemo'; -- noqa: PRS

SELECT
    USER_NAME() AS Usuario,
    IS_MEMBER('Auditor') AS EsAuditor,
    IS_MEMBER('DBA') AS EsDBA;

SELECT
    ID_HISTORIAL,
    NOMBRE_TABLA,
    REGISTRO_ID,
    OPERACION_REALIZADA,
    FECHA_CAMBIO,
    DESCRIPCION
FROM dbo.FN_CONSULTA_HISTORIAL();

REVERT;
GO


-- Consulta para buscar Personas Físicas
-- filtrando por su nombre y primer apellido

USE SISTEMADEFACTURACION;
GO

DECLARE @NOMBRE VARCHAR(50) = 'NOMBRE2';
DECLARE @APELLIDO1 VARCHAR(50) = 'APELLIDO2';

SELECT
    CF.ID_CLIENTE,
    CF.CEDULA,
    CF.NOMBRE,
    CF.APELLIDO1,
    CF.APELLIDO2,
    CF.CORREO_ELECTRONICO,
    CF.TELEFONO,
    CF.FECHA_REGISTRO,
    CF.ULTIMA_ACTUALIZACION,
    CF.ID_DIRECCION
FROM DBO.CLIENTE_FISICO AS CF
WHERE
    CF.NOMBRE = @NOMBRE
    AND CF.APELLIDO1 = @APELLIDO1;
GO

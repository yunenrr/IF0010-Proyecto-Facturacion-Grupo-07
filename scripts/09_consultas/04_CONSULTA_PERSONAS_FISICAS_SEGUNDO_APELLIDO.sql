-- Consulta para buscar Personas Físicas
-- filtrando por su nombre y segundo apellido

DECLARE @NOMBRE VARCHAR(100) = 'NOMBRE2';
DECLARE @APELLIDO2 VARCHAR(100) = 'APELLIDO2_2';

SELECT
    CF.ID_CLIENTE,
    CF.CEDULA,
    CF.NOMBRE,
    CF.APELLIDO1,
    CF.APELLIDO2,
    CF.CORREO_ELECTRONICO,
    CF.TELEFONO,
    CF.FECHA_REGISTRO,
    CF.ULTIMA_ACTUALIZACION,
    CF.ID_DIRECCION
FROM DBO.CLIENTE_FISICO AS CF
WHERE
    CF.NOMBRE = @NOMBRE
    AND CF.APELLIDO2 = @APELLIDO2;
GO

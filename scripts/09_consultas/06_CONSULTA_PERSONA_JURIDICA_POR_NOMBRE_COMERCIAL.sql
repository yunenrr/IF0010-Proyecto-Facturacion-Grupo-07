GO

DECLARE @NOMBRE_COMERCIAL VARCHAR(150) = 'COMERCIAL CLIENTE 1';

SELECT TOP (1000)
    CJ.ID_CLIENTE,
    CJ.CEDULA,
    CJ.RAZON_SOCIAL,
    CJ.NOMBRE_COMERCIAL,
    CJ.CORREO_ELECTRONICO,
    CJ.TELEFONO
FROM DBO.CLIENTE_JURIDICO AS CJ
WHERE CJ.NOMBRE_COMERCIAL LIKE '%' + @NOMBRE_COMERCIAL + '%';
GO

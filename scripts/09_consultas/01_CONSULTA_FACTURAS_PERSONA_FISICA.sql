USE SISTEMADEFACTURACION;
GO

DECLARE @CEDULA_FISICA VARCHAR(20) = '1-1002-0002';

SELECT TOP (1000)
    F.IDENTIFICADOR AS ID_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.IMPUESTOS_APLICADOS,
    F.MONTO_TOTAL,
    F.FECHA_CREACION,
    F.MODIFICACION,
    F.OBSERVACIONES,
    F.ID_EMPRESA,
    F.COD_IDENTIFICADOR_MONEDA,
    F.COD_IDENTIFICADOR_TIPO,
    F.COD_IDENTIFICADOR_ESTADO,
    CONCAT_WS(' ', CF.NOMBRE, CF.APELLIDO1, CF.APELLIDO2) AS NOMBRE_CLIENTE
FROM DBO.FACTURA AS F
INNER JOIN DBO.CLIENTE_FISICO AS CF
    ON F.ID_CLIENTE_FISICO = CF.ID_CLIENTE
WHERE CF.CEDULA = @CEDULA_FISICA
ORDER BY F.FECHA_EMISION DESC;
GO

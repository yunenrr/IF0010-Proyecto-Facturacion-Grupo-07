USE SISTEMADEFACTURACION;
GO

DECLARE @CEDULA_JURIDICA VARCHAR(20) = '3-101-000001';

SELECT
    F.IDENTIFICADOR AS ID_FACTURA,
    F.IDENTIFICADOR_COMPROBANTE,
    F.FECHA_EMISION,
    F.SUBTOTAL,
    F.TOTAL_DESCUENTOS,
    F.IMPUESTOS_APLICADOS,
    F.MONTO_TOTAL,
    F.FECHA_CREACION,
    F.MODIFICACION,
    F.OBSERVACIONES,
    F.ID_EMPRESA,
    F.COD_IDENTIFICADOR_MONEDA,
    F.COD_IDENTIFICADOR_TIPO,
    F.COD_IDENTIFICADOR_ESTADO,
    CJ.RAZON_SOCIAL AS NOMBRE_CLIENTE
FROM DBO.FACTURA AS F
INNER JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON F.ID_CLIENTE_JURIDICO = CJ.ID_CLIENTE
WHERE CJ.CEDULA = @CEDULA_JURIDICA
ORDER BY F.FECHA_EMISION DESC;
GO

DECLARE @ID_PRODUCTO INT = 1;
DECLARE @FECHA_INICIO DATE = '2026-01-01';
DECLARE @FECHA_FIN DATE = '2026-12-31';

SELECT
    F.IDENTIFICADOR AS ID_FACTURA,
    DF.CANTIDAD,
    F.FECHA_EMISION
FROM DBO.FACTURA AS F
INNER JOIN DBO.DETALLE_FACTURA AS DF
    ON F.IDENTIFICADOR = DF.IDENTIFICADOR_FACTURA
WHERE
    DF.ID_PRODUCTO = @ID_PRODUCTO
    AND F.FECHA_EMISION BETWEEN @FECHA_INICIO AND @FECHA_FIN
ORDER BY F.IDENTIFICADOR ASC;
GO

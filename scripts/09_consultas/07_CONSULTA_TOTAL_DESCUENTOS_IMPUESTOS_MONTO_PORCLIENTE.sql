DECLARE @CEDULA VARCHAR(20) = '1-1002-0002';

SELECT TOP (1000)
    ISNULL(SUM(F.TOTAL_DESCUENTOS), 0) AS TOTAL_DESCUENTOS,
    ISNULL(SUM(F.IMPUESTOS_APLICADOS), 0) AS TOTAL_IMPUESTOS,
    ISNULL(SUM(F.MONTO_TOTAL), 0) AS MONTO_TOTAL_FACTURADO
FROM DBO.FACTURA AS F
LEFT JOIN DBO.CLIENTE_FISICO AS CF
    ON F.ID_CLIENTE_FISICO = CF.ID_CLIENTE
LEFT JOIN DBO.CLIENTE_JURIDICO AS CJ
    ON F.ID_CLIENTE_JURIDICO = CJ.ID_CLIENTE
WHERE
    (
        CF.CEDULA = @CEDULA
        OR CJ.CEDULA = @CEDULA
    )
    AND YEAR(F.FECHA_EMISION) = YEAR(GETDATE());
GO

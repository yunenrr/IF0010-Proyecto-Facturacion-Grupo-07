USE SISTEMADEFACTURACION;
GO

DECLARE @RAZON_SOCIAL VARCHAR(150) = 'Empresa Cliente S.A. 1';

SELECT TOP (1000)
    CJ.ID_CLIENTE,
    CJ.CEDULA,
    CJ.RAZON_SOCIAL,
    CJ.NOMBRE_COMERCIAL,
    CJ.CORREO_ELECTRONICO,
    CJ.TELEFONO
FROM DBO.CLIENTE_JURIDICO AS CJ
WHERE CJ.RAZON_SOCIAL LIKE '%' + @RAZON_SOCIAL + '%';
GO
